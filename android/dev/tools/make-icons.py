"""Draws the OpenCharts Android icon (three candles and a trend line on a dark tile).

Writes the adaptive-icon vector parts, legacy launcher PNGs for Android 7 (API 24-25), the
splash drawable and the in-app start-screen image. Run again after changing the geometry:

    python dev/tools/make-icons.py
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "android" / "app" / "src" / "main" / "res"

BG = "#0B1015"
UP = "#0ECB81"
DOWN = "#F6465D"
LINE = "#22D3EE"

# Geometry on the 108 x 108 dp adaptive-icon canvas (the safe zone is the centre 66 dp).
CANDLES = [  # (x centre, wick top, body top, body bottom, wick bottom, colour)
    (38, 47, 53, 70, 76, UP),
    (54, 38, 44, 60, 66, DOWN),
    (70, 29, 35, 54, 60, UP),
]
BODY_W = 10
WICK_W = 2.4
TREND = [(29, 73), (45, 63), (57, 57), (79, 36)]
TREND_W = 3.4


def vector_foreground() -> str:
    """The adaptive icon's foreground layer as an Android vector drawable."""
    paths = []
    for x, wt, bt, bb, wb, colour in CANDLES:
        h = WICK_W / 2
        paths.append(f'<path android:fillColor="{colour}" android:pathData="M{x - h},{wt}h{WICK_W}v{wb - wt}h-{WICK_W}z"/>')
        b = BODY_W / 2
        paths.append(
            f'<path android:fillColor="{colour}" android:pathData="M{x - b + 1.5},{bt}h{BODY_W - 3}'
            f'a1.5,1.5 0 0 1 1.5,1.5v{bb - bt - 3}a1.5,1.5 0 0 1 -1.5,1.5h-{BODY_W - 3}'
            f'a1.5,1.5 0 0 1 -1.5,-1.5v-{bb - bt - 3}a1.5,1.5 0 0 1 1.5,-1.5z"/>'
        )
    trend = "M" + " L".join(f"{x},{y}" for x, y in TREND)
    paths.append(
        f'<path android:strokeColor="{LINE}" android:strokeWidth="{TREND_W}" android:strokeLineCap="round" '
        f'android:strokeLineJoin="round" android:fillColor="#00000000" android:pathData="{trend}"/>'
    )
    body = "\n    ".join(paths)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- OpenCharts icon: generated by dev/tools/make-icons.py -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
        f"    {body}\n"
        "</vector>\n"
    )


def raster(size: int, *, rounded: bool, inset: float = 0.0) -> Image.Image:
    """The icon as a PNG: the 108-unit canvas scaled to `size`, optionally zoomed past the margin."""
    scale = 4  # draw large, then downsample for smooth edges
    big = size * scale
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    radius = big * 0.22 if rounded else 0
    d.rounded_rectangle([0, 0, big - 1, big - 1], radius=radius, fill=BG)
    # Map the 108-unit canvas so the content fills more of a legacy icon (no adaptive mask).
    span = 108 - 2 * inset
    k = big / span

    def p(x: float, y: float) -> tuple[float, float]:
        return ((x - inset) * k, (y - inset) * k)

    for x, wt, bt, bb, wb, colour in CANDLES:
        d.rectangle([*p(x - WICK_W / 2, wt), *p(x + WICK_W / 2, wb)], fill=colour)
        d.rounded_rectangle([*p(x - BODY_W / 2, bt), *p(x + BODY_W / 2, bb)], radius=1.5 * k, fill=colour)
    pts = [p(x, y) for x, y in TREND]
    w = int(TREND_W * k)
    d.line(pts, fill=LINE, width=w, joint="curve")
    for x, y in pts[:1] + pts[-1:]:
        d.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=LINE)
    return img.resize((size, size), Image.LANCZOS)


def main() -> None:
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(vector_foreground(), encoding="utf-8")
    for old in RES.glob("mipmap-*/ic_launcher_foreground.png"):
        old.unlink()
    # Capacitor's template icon: drawable-v24 wins over drawable/ on Android 7+, so the
    # launcher showed the Capacitor logo instead of ours while it was there.
    for old in (RES / "drawable-v24" / "ic_launcher_foreground.xml", RES / "drawable" / "ic_launcher_background.xml"):
        old.unlink(missing_ok=True)
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background"/>\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>\n'
        "</adaptive-icon>\n"
    )
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (RES / "mipmap-anydpi-v26" / name).write_text(adaptive, encoding="utf-8")
    (RES / "values" / "ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{BG}</color>\n</resources>\n',
        encoding="utf-8",
    )
    for folder, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        out = RES / f"mipmap-{folder}"
        out.mkdir(parents=True, exist_ok=True)
        raster(px, rounded=True, inset=14).save(out / "ic_launcher.png")
        raster(px, rounded=True, inset=14).save(out / "ic_launcher_round.png")
    # The terminal's start screen and web icons.
    icons = ROOT.parent / "upstream" / "public" / "icons"
    raster(192, rounded=True, inset=14).save(icons / "app-icon-192.png")
    raster(512, rounded=True, inset=14).save(icons / "app-icon-512.png")
    print("icons written")


if __name__ == "__main__":
    main()
